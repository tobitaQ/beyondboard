"""Embed the selected JPEG files in a C header, so that the on-device and the
cloud sketches process exactly the same bytes.

Usage: python3 make_header.py IMAGES_DIR OUT_HEADER
"""
import os
import sys

from PIL import Image


def main():
    src, out = sys.argv[1], sys.argv[2]
    names = sorted(f for f in os.listdir(src) if f.endswith(".jpg"))
    with open(out, "w") as h:
        h.write("// Generated by make_header.py. Not in Git (WIDER FACE images, CC BY-NC-ND 4.0).\n#pragma once\n#include <Arduino.h>\n\n")
        for i, name in enumerate(names):
            data = open(os.path.join(src, name), "rb").read()
            h.write(f"static const uint8_t IMG{i}[] PROGMEM = {{")
            h.write(",".join(str(b) for b in data))
            h.write("};\n")
        h.write("\nstruct TestImage { const char* id; const uint8_t* data; size_t length; int width; int height; };\n")
        h.write("static const TestImage IMAGES[] = {\n")
        for i, name in enumerate(names):
            with Image.open(os.path.join(src, name)) as im:
                w, hgt = im.size
            h.write(f'  {{"{name[:-4]}", IMG{i}, sizeof(IMG{i}), {w}, {hgt}}},\n')
        h.write("};\nstatic const size_t IMAGE_COUNT = sizeof(IMAGES) / sizeof(IMAGES[0]);\n")
    print(len(names), "images ->", out)


if __name__ == "__main__":
    main()
